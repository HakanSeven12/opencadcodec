use super::*;
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct StoredPlotSettings {
    handle: Handle,
    owner: Handle,
    reactors: Vec<Handle>,
    #[serde(deserialize_with = "crate::storage::records::required_option")]
    xdictionary_handle: Option<Handle>,
    page_name: String,
    printer_name: String,
    paper_size: String,
    plot_view_name: String,
    current_style_sheet: String,
    paper_width: f64,
    paper_height: f64,
    margins: PaperMargin,
    origin_x: f64,
    origin_y: f64,
    plot_window: PlotWindow,
    scale_numerator: f64,
    scale_denominator: f64,
    paper_units: PlotPaperUnits,
    rotation: PlotRotation,
    plot_type: PlotType,
    scale_type: ScaledType,
    shade_plot_mode: ShadePlotMode,
    shade_plot_resolution: ShadePlotResolutionLevel,
    shade_plot_dpi: i16,
    flags: PlotFlags,
    standard_scale_factor: f64,
    paper_image_origin_x: f64,
    paper_image_origin_y: f64,
    plot_view_handle: Handle,
    visual_style_handle: Handle,
}
